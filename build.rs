// 从 holidays.txt 计算 A 股交易日，嵌入二进制，并同步写出 tradeday/{year}.txt

use std::collections::{BTreeMap, BTreeSet};
use std::env;
use std::fs;
use std::path::Path;

use chrono::{Datelike, Duration, NaiveDate, Weekday};

fn main() {
    let holidays_path = Path::new("holidays.txt");
    println!("cargo:rerun-if-changed=holidays.txt");

    let holidays = load_holidays(holidays_path);
    let years: BTreeSet<i32> = holidays.iter().map(NaiveDate::year).collect();
    assert!(!years.is_empty(), "holidays.txt must contain at least one holiday date");

    let tradeday_dir = Path::new("tradeday");
    fs::create_dir_all(tradeday_dir).expect("create tradeday directory");

    let mut by_year: BTreeMap<i32, Vec<NaiveDate>> = BTreeMap::new();
    for year in years {
        by_year.insert(year, trading_days_for_year(year, &holidays));
    }

    let mut combined = String::new();
    let mut all_dates: Vec<NaiveDate> = Vec::new();

    for (year, days) in &by_year {
        write_year_file(tradeday_dir, *year, days);
        println!("cargo:rerun-if-changed=tradeday/{year}.txt");

        combined.push_str(&format!(
            "# Generated by build.rs from holidays.txt\n\
             # Source: weekdays minus public holidays\n\
             # Year: {year}\n\
             \n"
        ));
        for day in days {
            combined.push_str(&day.format("%Y-%m-%d").to_string());
            combined.push('\n');
            all_dates.push(*day);
        }
        combined.push('\n');
    }

    let (first, last) = (
        all_dates.first().expect("no trading days generated"),
        all_dates.last().expect("no trading days generated"),
    );
    println!(
        "cargo:rustc-env=DATA_FIRST={}",
        first.format("%Y-%m-%d")
    );
    println!("cargo:rustc-env=DATA_LAST={}", last.format("%Y-%m-%d"));

    let out_dir = env::var("OUT_DIR").expect("OUT_DIR not set");
    fs::write(Path::new(&out_dir).join("trading_days.txt"), combined)
        .expect("write trading_days.txt");
}

fn load_holidays(path: &Path) -> BTreeSet<NaiveDate> {
    let text = fs::read_to_string(path).unwrap_or_else(|err| {
        panic!("read {}: {err}", path.display());
    });

    let mut holidays = BTreeSet::new();
    for (lineno, raw) in text.lines().enumerate() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }

        let (range, _) = line
            .split_once(char::is_whitespace)
            .map(|(range, rest)| (range, Some(rest)))
            .unwrap_or((line, None));

        let (start_raw, end_raw) = match range.split_once("..") {
            Some((start, end)) => (start, end),
            None => (range, range),
        };

        let start = parse_iso(start_raw).unwrap_or_else(|| {
            panic!(
                "{}:{}: invalid start date in `{raw}`",
                path.display(),
                lineno + 1
            )
        });
        let end = parse_iso(end_raw).unwrap_or_else(|| {
            panic!(
                "{}:{}: invalid end date in `{raw}`",
                path.display(),
                lineno + 1
            )
        });
        if end < start {
            panic!(
                "{}:{}: range end before start in `{raw}`",
                path.display(),
                lineno + 1
            );
        }

        let mut day = start;
        while day <= end {
            holidays.insert(day);
            day += Duration::days(1);
        }
    }

    holidays
}

fn parse_iso(raw: &str) -> Option<NaiveDate> {
    NaiveDate::parse_from_str(raw, "%Y-%m-%d").ok()
}

fn trading_days_for_year(year: i32, holidays: &BTreeSet<NaiveDate>) -> Vec<NaiveDate> {
    let start = NaiveDate::from_ymd_opt(year, 1, 1).expect("valid year start");
    let end = NaiveDate::from_ymd_opt(year, 12, 31).expect("valid year end");
    let mut days = Vec::new();
    let mut day = start;
    while day <= end {
        if day.weekday() != Weekday::Sat
            && day.weekday() != Weekday::Sun
            && !holidays.contains(&day)
        {
            days.push(day);
        }
        day += Duration::days(1);
    }
    days
}

fn write_year_file(dir: &Path, year: i32, days: &[NaiveDate]) {
    let path = dir.join(format!("{year}.txt"));
    let mut text = format!(
        "# Generated by build.rs from holidays.txt\n\
         # Source: weekdays minus public holidays\n\
         # Year: {year}\n\
         \n"
    );
    for day in days {
        text.push_str(&day.format("%Y-%m-%d").to_string());
        text.push('\n');
    }

    // 内容未变则不写，避免无意义刷新 mtime
    if path.is_file()
        && fs::read_to_string(&path)
            .map(|old| old == text)
            .unwrap_or(false)
    {
        return;
    }
    fs::write(&path, text).unwrap_or_else(|err| {
        panic!("write {}: {err}", path.display());
    });
}
